#!/usr/bin/env python3
"""The one product version source: VERSION, and everything derived from it.

Product SemVer lives only in the repository-root VERSION file. This script
regenerates the committed codec-version header (`--write`), verifies that
the header agrees with VERSION (`--check`, read-only,
used by the drift generated-files check), prints the development identity
of a checkout (`--dev`), and validates release tags (`--tag`). The product
version is independent of the C API version (`rf_version()`) and of the
.fold format version; neither is read or changed here.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEMVER = re.compile(r'^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-((?:0|[1-9][0-9]*|[0-9]*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9][0-9]*|[0-9]*[a-zA-Z-][0-9a-zA-Z-]*))*))?$')
HEADER_REL = 'src/product_version.h'


def root_of(args) -> Path:
    return Path(args.root).resolve() if getattr(args, 'root', None) else ROOT


def read_version(root: Path) -> str:
    path = root / 'VERSION'
    try:
        text = path.read_text(encoding='utf-8').strip()
    except OSError as exc:
        raise ValueError(f'{path}: unreadable VERSION ({exc})') from exc
    if not SEMVER.fullmatch(text):
        raise ValueError(f'{path}: not a SemVer product version: {text!r}')
    return text


def header_text(version: str) -> str:
    major, minor, patch = SEMVER.fullmatch(version).group(1, 2, 3)
    prerelease = SEMVER.fullmatch(version).group(4)
    lines = [
        '/* Generated by scripts/version.py from VERSION; do not edit by hand. */',
        '#pragma once',
        '',
        f'#define RF_PRODUCT_VERSION "{version}"',
        f'#define RF_PRODUCT_VERSION_MAJOR {major}u',
        f'#define RF_PRODUCT_VERSION_MINOR {minor}u',
        f'#define RF_PRODUCT_VERSION_PATCH {patch}u',
    ]
    if prerelease:
        lines.append(f'#define RF_PRODUCT_VERSION_PRERELEASE "{prerelease}"')
    return '\n'.join(lines) + '\n'


def git_state(root: Path) -> tuple[str, bool | None]:
    def git(*argv: str) -> str | None:
        try:
            result = subprocess.run(
                ['git', '-C', str(root), *argv],
                capture_output=True, text=True, timeout=30,
            )
        except (OSError, subprocess.SubprocessError):
            return None
        return result.stdout.strip() if result.returncode == 0 else None

    revision = git('rev-parse', '--short=12', 'HEAD')
    if revision is None:
        return 'unknown', None
    status = git('status', '--porcelain')
    if status is None:
        return revision, None
    return revision, bool(status)


def dev_label(version: str, revision: str, dirty: bool | None) -> str:
    label = f'{version}-dev+{revision}'
    if revision == 'unknown':
        return label
    if dirty is True:
        label += '.dirty'
    elif dirty is None:
        label += '.status-unknown'
    return label


def checkout_dev_label(root: Path) -> str:
    revision, dirty = git_state(root)
    return dev_label(read_version(root), revision, dirty)


def check_tag(tag: str, version: str) -> None:
    if '+' in tag:
        raise ValueError(f'{tag}: build metadata is not permitted in a release tag')
    prefix = 'rasterfold-v'
    if not tag.startswith(prefix):
        raise ValueError(f'{tag}: release tags are named {prefix}<SemVer>')
    tagged = tag[len(prefix):]
    if not SEMVER.fullmatch(tagged):
        raise ValueError(f'{tag}: not a SemVer release tag')
    if tagged != version:
        raise ValueError(
            f'{tag}: tag version {tagged} does not match VERSION {version}; '
            'a prerelease tag requires the identical prerelease in VERSION'
        )


def check(root: Path) -> list[str]:
    # The header is the only derived file this tool owns. Agreement of
    # docs/facts.json and the site citation with VERSION is enforced by
    # drift's product_version fact and its generated-facts comparison.
    version = read_version(root)
    problems = []
    header = root / HEADER_REL
    if not header.is_file():
        problems.append(f'{HEADER_REL}: missing; run scripts/version.py --write')
    elif header.read_text(encoding='utf-8') != header_text(version):
        problems.append(f'{HEADER_REL}: disagrees with VERSION {version}; run scripts/version.py --write')
    return problems


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', help='repository root (default: this checkout)')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='regenerate src/product_version.h from VERSION')
    mode.add_argument('--check', action='store_true', help='verify derived version identities agree (read-only)')
    mode.add_argument('--dev', action='store_true', help='print the development identity of the checkout')
    mode.add_argument('--tag', metavar='TAG', help='validate a release tag against VERSION')
    args = parser.parse_args(argv)
    root = root_of(args)
    try:
        if args.write:
            version = read_version(root)
            target = root / HEADER_REL
            target.write_text(header_text(version), encoding='utf-8', newline='\n')
            print(f'{HEADER_REL}: product version {version}')
        elif args.check:
            problems = check(root)
            for problem in problems:
                print(f'version: {problem}')
            if problems:
                return 1
            print(f'version: product {read_version(root)} agrees with the generated header')
        elif args.dev:
            print(checkout_dev_label(root))
        elif args.tag:
            check_tag(args.tag, read_version(root))
            print(f'{args.tag}: matches VERSION {read_version(root)}')
        else:
            print(read_version(root))
    except ValueError as exc:
        print(f'version: {exc}')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
